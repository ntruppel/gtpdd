def espnJson(url):
    # GETs an ESPN endpoint and returns the parsed JSON
    r = requests.get(url, timeout=20)
    r.raise_for_status()
    return r.json()


def seasonSchedule(teamID=TEAM_ID, year=None):
    # Returns (season year, games oldest first), with what's needed to score and display each game
    url = ESPN_SCHEDULE_URL.format(teamID)
    if year:
        url += f'?season={year}'
    x = espnJson(url)
    season = (x.get('requestedSeason') or x.get('season') or {}).get('year')
    season = int(season or year or datetime.now().year)

    games = []
    # Find our side and the opponent's side of each game
    for event in x.get('events', []):
        comp = (event.get('competitions') or [{}])[0]
        us = them = None
        for c in comp.get('competitors', []):
            if str(c.get('team', {}).get('id')) == str(teamID):
                us = c
            else:
                them = c
        if us is None or them is None:
            continue

        completed = bool(((comp.get('status') or {}).get('type') or {}).get('completed'))
        pf = (us.get('score') or {}).get('value')
        pa = (them.get('score') or {}).get('value')
        games.append({
            'gameID': str(event.get('id')),
            'startDate': comp.get('date') or event.get('date'),
            'opponent': them['team'].get('location') or them['team'].get('displayName'),
            'logoUrl': teamLogoUrl(them['team']),
            'setting': 'Neutral' if comp.get('neutralSite')
                       else ('Home' if us.get('homeAway') == 'home' else 'Away'),
            'completed': completed,
            # Unplayed games show 0-0, so only read the score once the game is final
            'pf': int(pf) if completed and pf is not None else None,
            'pa': int(pa) if completed and pa is not None else None,
        })
    games.sort(key=lambda g: g['startDate'] or '')
    return season, games


def teamLogoUrl(team):
    # Returns ESPN's standard (light-background) logo URL for a team
    logos = team.get('logos') or []
    for wanted in ('default', 'dark'):
        for logo in logos:
            if wanted in (logo.get('rel') or []) and logo.get('href'):
                return logo['href']
    return logos[0].get('href') if logos else None


def publishOpponentLogo(name, url):
    # Caches an opponent's logo and publishes a table-sized copy; returns its page link or None
    if not name or not url:
        return None
    slug = assetSlug(name)
    src = os.path.join(LOGO_DIR, f"{name}.png")
    if not os.path.isfile(src) and not downloadLogo(url, src, name):
        return None
    img = trimmedLogo(src)
    if img is None:
        return None
    # Shrink to table size, allowing wide wordmarks up to 2.5x the height
    img.thumbnail((round(LOGO_HEIGHT * 2.5), LOGO_HEIGHT), Image.LANCZOS)
    os.makedirs(WEB_LOGO_DIR, exist_ok=True)
    img.save(os.path.join(WEB_LOGO_DIR, slug + '.png'))
    return 'logo/' + slug + '.png'


def getPrediction(gameID, teamID=TEAM_ID):
    # Returns Tech's FPI win percentage for a game, or None if ESPN has no projection (e.g. some FCS games)
    try:
        x = espnJson(ESPN_SUMMARY_URL.format(gameID))
        predictor = x['predictor']
    except Exception as e:
        print(f"  No FPI for game {gameID} ({type(e).__name__}: {e}).")
        return None
    # Read the projection from Tech's side of the matchup
    try:
        side = 'homeTeam' if str(predictor['homeTeam']['id']) == str(teamID) else 'awayTeam'
        return float(predictor[side]['gameProjection'])
    except (KeyError, TypeError, ValueError):
        print(f"  No FPI projection for game {gameID}.")
        return None


def gameOdds(games, teamID=TEAM_ID):
    # Sets each game's win odds (1/0/0.5 if played, FPI otherwise) and its source for the page
    for g in games:
        if g['completed'] and g['pf'] is not None and g['pa'] is not None:
            g['odds'] = 1.0 if g['pf'] > g['pa'] else (0.0 if g['pf'] < g['pa'] else 0.5)
            g['source'] = 'final'
            continue
        projection = getPrediction(g['gameID'], teamID)
        if projection is None:
            # No FPI: count it as a coin flip rather than dropping it from the schedule
            g['odds'], g['source'] = 0.5, 'even'
        else:
            g['odds'], g['source'] = round(projection / 100, 4), 'fpi'
    return games


####
# ODDS MATH
####

def winDistribution(odds):
    # Returns P(exactly k wins) for k = 0..len(odds), treating every game as independent
    dist = np.zeros(len(odds) + 1)
    dist[0] = 1.0
    # Fold in each game: a win shifts the odds up one win, a loss leaves them in place
    for i, p in enumerate(odds):
        dist[1:i + 2] = dist[1:i + 2] * (1 - p) + dist[0:i + 1] * p
        dist[0] *= (1 - p)
    return dist


def recordLabels(n):
    # Record labels for every possible finish, e.g. n=12 -> '0-12' ... '12-0'
    return [f"{k}-{n - k}" for k in range(n + 1)]


def teamRecord(games):
    # Tech's current record from the games already played, e.g. '3-2'
    wins = sum(1 for g in games if g.get('source') == 'final' and g['odds'] == 1.0)
    losses = sum(1 for g in games if g.get('source') == 'final' and g['odds'] == 0.0)
    return f"{wins}-{losses}"


