def snapshot(games, dist, when):
    # Packages one run (odds, summary numbers and schedule) as the page reads it
    schedule = []
    # One schedule entry per game, with its logo and final score when available
    for g in games:
        entry = {'date': gameDayText(g), 'opponent': g['opponent'], 'setting': g['setting'],
                 'odds': round(float(g['odds']), 4), 'source': g['source']}
        logo = publishOpponentLogo(g['opponent'], g.get('logoUrl'))
        if logo:
            entry['logo'] = logo
        if g['source'] == 'final':
            entry['pf'], entry['pa'] = g['pf'], g['pa']
        schedule.append(entry)
    return {
        'date': when.strftime('%Y-%m-%d'),
        'label': runLabel(games, when),
        'dateLabel': f"{when:%B} {when.day}, {when.year}",
        'record': teamRecord(games),
        'expectedWins': round(sum(g['odds'] for g in games), 3),
        'bowlOdds': round(float(dist[BOWL_WINS:].sum()), 5),
        'odds': [round(float(v), 5) for v in dist],
        'schedule': schedule,
    }


def runsJs(data):
    # Formats runs.js by hand, one line per odds list and game, so it stays readable and diffs cleanly
    out = ['{',
           '  "years": ' + json.dumps(data['years']) + ',',
           '  "bowlWins": ' + json.dumps(data['bowlWins']) + ',',
           '  "runs": {']
    years = sorted(data['runs'], key=int)
    for yi, year in enumerate(years):
        runs = data['runs'][year]
        out.append('    "%s": [' % year)
        for ri, r in enumerate(runs):
            out += ['      {',
                    '        "date": %s, "label": %s, "dateLabel": %s, "record": %s,'
                    % (json.dumps(r['date']), json.dumps(r['label']),
                       json.dumps(r['dateLabel']), json.dumps(r['record'])),
                    '        "expectedWins": %s, "bowlOdds": %s,'
                    % (json.dumps(r['expectedWins']), json.dumps(r['bowlOdds'])),
                    '        "odds": ' + json.dumps(r['odds']) + ',',
                    '        "schedule": [']
            for gi, g in enumerate(r['schedule']):
                out.append('          ' + json.dumps(g)
                           + (',' if gi < len(r['schedule']) - 1 else ''))
            out += ['        ]', '      }' + (',' if ri < len(runs) - 1 else '')]
        out.append('    ]' + (',' if yi < len(years) - 1 else ''))
    out += ['  }', '}']
    return '\n'.join(out)


def normalizeRun(run):
    # Fills in fields the page now needs on runs saved by older versions of this script
    run = dict(run)
    run.setdefault('dateLabel', run.get('label') or run.get('date', ''))
    if run.get('label') in (None, run['dateLabel']):
        # Old date-style labels become 'Before Game N' from the run's schedule (bye weeks can't be recovered)
        schedule = run.get('schedule') or []
        played = sum(1 for g in schedule if g.get('source') == 'final')
        run['label'] = 'Final' if played >= len(schedule) else f"Before Game {played + 1}"

    # Add logos published since the run was saved, so older runs show them too
    schedule = []
    for g in run.get('schedule') or []:
        g = dict(g)
        if 'logo' not in g and g.get('opponent'):
            link = 'logo/' + assetSlug(g['opponent']) + '.png'
            if os.path.isfile(os.path.join(HTML_DIR, link)):
                g['logo'] = link
        schedule.append(g)
    run['schedule'] = schedule
    return run


def saveRun(season, run, path=None):
    # Adds this run to the run history, replacing any run from the same day
    path = path or RUNS_PATH
    stored = readJsGlobal(path, JS_GLOBAL) or {}
    # Load every stored run, upgrading older ones on the way
    runs = {str(y): [normalizeRun(r) for r in v]
            for y, v in (stored.get('runs') or {}).items()}

    # Drop any run from the same date, then add this one in date order
    season_runs = [r for r in runs.get(str(season), []) if r.get('date') != run['date']]
    replaced = len(season_runs) < len(runs.get(str(season), []))
    season_runs.append(run)
    season_runs.sort(key=lambda r: r['date'])
    runs[str(season)] = season_runs

    # Rewrite runs.js with seasons newest first
    years = sorted((int(y) for y in runs), reverse=True)
    writeJsGlobal(path, JS_GLOBAL,
                  {'years': years, 'bowlWins': BOWL_WINS, 'runs': runs},
                  header=RUNS_JS_HEADER, dumps=runsJs)
    print(f"{'Replaced' if replaced else 'Added'} the {run['date']} run in {path}: "
          f"{len(season_runs)} runs on file for {season}")
    return path


