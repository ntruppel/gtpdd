def gameDayText(game):
    # Kickoff date as 'Sep 5', or blank if unknown
    when = gameDateTime(game)
    return '' if when is None else f"{when:%b} {when.day}"


def runLabel(games, when):
    # Names a run by where it falls in the season ('Before Game 4'), as shown in the run selector
    played = sum(1 for g in games if g['source'] == 'final')
    if played >= len(games):
        return 'Final'
    if played == 0:
        return 'Before Game 1'

    # A run more than a week after the last game, with a bye before the next, is the bye-week run
    last, nxt = gameDateTime(games[played - 1]), gameDateTime(games[played])
    if last and nxt and (nxt.date() - last.date()).days > 8 \
            and (when.date() - last.date()).days > 7:
        return 'After Bye Week'
    return f"Before Game {played + 1}"


def drawChart(dist, records, figPath, backgroundPath, color1, color2, datestring):
    # Draws the posted PNG: the record odds as bars in Tech's ESPN colors, over the stadium photo
    odds = list(dist)
    fig, ax = plt.subplots()
    fig.set_size_inches(20, 10)
    # One bar per record, with its odds above and the record below
    for i, v in enumerate(odds):
        ax.bar(i, v, color='#' + color1, edgecolor='#' + color2, linewidth=3, hatch='x')
        offset = -0.012 if v > .01 else 0.005
        ax.text(i, v + offset, "{:.1%}".format(v), ha='center', fontsize=19, color='white',
                path_effects=[pe.withStroke(linewidth=2, foreground='black')])
        ax.text(i, -0.005, records[i], ha='center', va='top', fontsize=20, color='white',
                path_effects=[pe.withStroke(linewidth=2, foreground='black')])

    ax.set_ylim([0, max(odds) + 0.05])
    ax.axis('off')
    ax.set_title("Using ESPN's FPI | " + str(datestring), fontsize=30, color='black')
    plt.suptitle('Louisiana Tech Record Predictor', fontsize=45, color='black', fontweight='bold')
    os.makedirs(os.path.dirname(figPath) or '.', exist_ok=True)
    fig.savefig(figPath, bbox_inches='tight', pad_inches=0, dpi=100, transparent=True)
    plt.close(fig)

    # Center the transparent chart on the background photo
    img = Image.open(figPath, 'r')
    img_w, img_h = img.size
    background = Image.open(backgroundPath, 'r')
    bg_w, bg_h = background.size
    offset = ((bg_w - img_w) // 2, (bg_h - img_h) // 2)
    background.paste(img, offset, img)
    background.save(figPath)
    return figPath


def writePreviewCard(png_path, dest):
    # Saves the link-preview card: the whole chart on a Tech-blue card, since cropping cuts the record labels
    try:
        img = Image.open(png_path).convert('RGB')
    except Exception as e:
        print(f"Could not read {png_path} ({type(e).__name__}: {e}); the page gets no preview image.")
        return None
    W, H = PREVIEW_SIZE
    scale = min(W / img.width, H / img.height)
    img = img.resize((round(img.width * scale), round(img.height * scale)), Image.LANCZOS)
    card = Image.new('RGB', PREVIEW_SIZE, PREVIEW_BG)
    card.paste(img, ((W - img.width) // 2, (H - img.height) // 2))
    os.makedirs(os.path.dirname(dest) or '.', exist_ok=True)
    card.save(dest, quality=88, optimize=True)
    return os.path.basename(dest)


