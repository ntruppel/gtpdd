def fbRecordPredictor(platform='AWS', year=None, html=True, teamID=TEAM_ID):
    # Output and background paths differ between the AWS box and Windows
    if platform == 'Windows':
        figPath = r'out_files/fbRecordPredictor.png'
        backgroundPath = r'in_files\backgrounds\fbRecordPredictor.png'
    else:
        figPath = 'out/fbRecordPredictor.png'
        backgroundPath = 'img/fbRecordPredictorBackground.png'

    # Pull the schedule and every game's win odds
    season, games = seasonSchedule(teamID, year)
    if not games:
        print(f"ESPN lists no {season} games for team {teamID}; nothing to predict.")
        return None
    print(f"{season}: {len(games)} games on the schedule")

    gameOdds(games, teamID)
    # Print each game's result or odds
    for g in games:
        played = g['source'] == 'final'
        print(f"  {gameDayText(g):>7}  {g['opponent'][:26]:<26} {g['setting']:<7} "
              + (f"{g['pf']}-{g['pa']}" if played else f"{g['odds']:.1%}"
                 + ('' if g['source'] == 'fpi' else ' (no FPI, held even)')))

    # Combine the game odds into odds for every final record
    dist = winDistribution([g['odds'] for g in games])
    records = recordLabels(len(games))
    now = datetime.now()
    run = snapshot(games, dist, now)

    # Posted PNG, using Tech's ESPN colors
    drawChart(dist, records, figPath, backgroundPath,
              *getTeamInfo(teamID)[1:], now.strftime("%B %d, %Y"))
    print(f"Wrote {figPath}")

    # File this run and rebuild the page
    if html:
        saveRun(season, run)
        writeSite(season, run, figPath)

    # Caption for the post, with bowl odds unless they're already 0% or 100%
    status = ("Using ESPN's FPI, here are the odds on how Tech's record will look "
              "at the end of the regular season")
    if 0 < run['bowlOdds'] < 1:
        status += (". Right now ESPN gives Tech a " + f"{run['bowlOdds']:.2%}"
                   + " chance to make a bowl game:")
    print(status)
    return run


